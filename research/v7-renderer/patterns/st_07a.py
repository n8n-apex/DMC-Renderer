"""Pattern for ST-07A — Case Study (Plan B flagship rebuild).

DATA-PREP ONLY. This module reads the package `page` dict, builds the QR
SVG, resolves the portrait URI, shapes a context dict, and renders
`templates/st_07a.html.jinja` (which composes the atomic macro library on a
token-themed layout, `styles/st_07a.css`). The returned PageFragment.html is
that rendered string; the .css is the layout sheet's contents.

WHY this shape (vs the old hand-built f-string CSS):
  - Brand-agnostic by construction: the template + layout CSS contain ZERO
    client literals (no hex, no font family, no client name). Colors + fonts
    arrive at render time via the token `:root` (compile_tokens) — the headline
    sizes off `var(--font-display)`, which resolves to the SERIF face when the
    brand's axis is headline_type=serif (the apex deck IS serif).
  - The component LOOK (pill / stat-strip / pull-quote / qr / section-label /
    media) lives in styles/components.css (already in the shared <head>); this
    pattern only feeds the macros DATA and positions them.

DATA CONTRACT (fields on page["data"]):
  kurzportraet, ausgangsproblem, ziel, loesung, ergebnis_text,
  ergebnis_headline, fallstudie_number, pullquote.{text,attribution},
  kunde.{name,company_url} (+ optional funktion = role),
  ergebnis_metrics[] (list of {label,value} dicts OR "label: value" strings).
  Plus brand.qr_target_url, brand.company_url_display.

CLIENT PORTRAIT — v2.0 `slots[]` (DNA §C2, the FIXED case-study photo slot):
  ctx.slot_uri(page, "case_study_portrait") (the single-photo primitive).
  - RESOLVED (e.g. apex Fallstudie 3 / Frese) → a LARGE framed portrait at the top
    of the sidebar (DNA §C2: a named client face, full-color, never tiny) beside
    name/role/own-URL + QR.
  - ABSENT (the other apex case studies, status "missing_required") → the template
    renders NO photo AND NO empty placeholder box (an explicit OWNER decision: a
    missing case-study photo must render beautifully WITHOUT a frame, never an
    empty grey plate). The sidebar reflows cleanly to the name/role/url block + the
    QR/pull-quote panel. This closes DNA gap #3 (empty case-study photo boxes).

Body fields go through preprocess.preprocess_body (markdown → HTML). The QR is
generated by patterns._components.qr_svg (shared impl).

NON-EMPTY-SECTION LOGIC (preserved): a body section is emitted ONLY when its
content is non-empty. Some case studies have an empty `ziel` (WENDEPUNKT
absent); rendering an empty section wastes vertical space and can push the
longest case study onto a 2nd physical page.

The German section headings (Ausgangssituation / Ziel / Lösung / Ergebnis) and
the FALLSTUDIE kicker are CONTENT labels for this report type — defined as
module constants here (not scattered, not client-specific) and passed to the
template as data.

History (Plan B): replaced the prior monolithic f-string render (hand-written
.lrp-grid CSS with hardcoded color + font-family literals baked into the
pattern) with this data-prep → Jinja-template split. Grammar required-present checks +
chassis_config keep-alive retained. Earlier history (Move 2c, design_preferences
deletion, CoralValidator→AccentBudgetValidator) documented in git.
"""

